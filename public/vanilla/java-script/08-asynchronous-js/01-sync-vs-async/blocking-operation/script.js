"use strict";

// Функція для створення штучного блокування потоку на N мілісекунд
function blockThread(ms) {
    const start = Date.now();
    // Порожній цикл, який повністю завантажує процесор і зупиняє Event Loop
    while (Date.now() - start < ms) {
        // Блокування потоку...
    }
}

console.log("1. Початок скрипту");

// Запускаємо асинхронну операцію (таймаут на 1 секунду)
setTimeout(() => {
    console.log("3. Асинхронна операція виконана (setTimeout)");
}, 1000);

console.log("2. Запуск блокуючої операції на 3 секунди...");

// Блокуємо головний потік на 3 секунди
blockThread(3000);

console.log("4. Блокуюча операція завершена, потік звільнено");