"use strict";

// Функція, яка імітує асинхронне завантаження даних користувача
function fetchUserData(userId, callback) {
    console.log(`[1] Запит даних для користувача з ID: ${userId}...`);

    // Імітуємо затримку мережі в 2 секунди (2000 мс)
    setTimeout(() => {
        // Дані, які ми "отримали" від сервера
        const user = {
            id: userId,
            name: "Олексій",
            role: "Developer"
        };

        console.log("[2] Дані успішно отримані від сервера!");

        // Викликаємо callback-функцію і передаємо туди результат
        callback(user);
    }, 5000);
}

// === Використання функції ===

console.log("Початок програми");

// Викликаємо функцію та передаємо колбек як другий аргумент
fetchUserData(42, (data) => {
    console.log("[3] Колбек спрацював. Отримані дані:", data);
});

console.log("Кінець програми (код продовжує виконуватися далі)");